#!/usr/bin/env bash
# Builds the playground into playground/web: compiles dog4 to WebAssembly and
# turns the repository's examples into examples.js.
#
#   playground/build.sh          # then serve playground/web, e.g.
#   python3 -m http.server -d playground/web
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(dirname "$here")"

cargo build --release --target wasm32-unknown-unknown --manifest-path "$here/Cargo.toml"
cp "$here/target/wasm32-unknown-unknown/release/dog4_playground.wasm" "$here/web/dog4.wasm"

python3 - "$root" "$here/web/examples.js" <<'PY'
import json, pathlib, sys

root, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
# (title, file) in menu order. Header comments for the test harness are dropped.
menu = [
    ("Hello, blocks", "hello"),
    ("Loops are folds", "folds"),
    ("One function, five meanings", "shapeshift"),
    ("Gluing is folding too", "glue"),
    ("Events from closures", "events"),
    ("References", "references"),
    ("Overloads by type", "overloads"),
    ("Errors and the sandbox", "sandbox"),
    ("FizzBuzz", "fizzbuzz"),
    ("Chat-bot commands", "bot"),
    ("Inventory with references", "inventory"),
    ("HTML templates", "html"),
]
examples = []
for title, name in menu:
    lines = (root / "examples" / f"{name}.dog").read_text().splitlines()
    while lines and lines[0].startswith(("// limits:", "// fuel:", "// deny:", "// output:")):
        lines.pop(0)
    examples.append({"title": title, "code": "\n".join(lines) + "\n"})
out.write_text(
    "// Generated by playground/build.sh from examples/*.dog. Don't edit.\n"
    f"export const EXAMPLES = {json.dumps(examples, indent=2, ensure_ascii=False)};\n"
)
PY
echo "built $here/web ($(du -h "$here/web/dog4.wasm" | cut -f1) of WebAssembly)"
